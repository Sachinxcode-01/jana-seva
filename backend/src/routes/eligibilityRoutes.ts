import { Router, Response } from 'express';
import { db } from '../database/db.js';
import { optionalAuthenticate, AuthenticatedRequest } from '../auth/authMiddleware.js';
import { evaluateEligibility, EligibilityInput } from '../services/eligibilityEngine.js';
import { EligibilityAssessment } from '../types.js';

const router = Router();

// POST /api/eligibility/check
router.post('/check', optionalAuthenticate, (req: AuthenticatedRequest, res: Response) => {
  try {
    const {
      age,
      state,
      occupation,
      gender,
      beneficiaryCategory,
      annualIncome,
      educationLevel,
      hasBPLCard
    } = req.body;

    if (age === undefined || !state || !occupation || !beneficiaryCategory) {
      return res.status(400).json({
        success: false,
        message: 'Age, state, occupation, and beneficiary category are required.'
      });
    }

    const input: EligibilityInput = {
      age: Number(age),
      state: String(state),
      occupation: String(occupation),
      gender: (gender as 'Female' | 'Male' | 'Other') || 'Other',
      beneficiaryCategory: String(beneficiaryCategory),
      annualIncome: Number(annualIncome) || 0,
      educationLevel: educationLevel ? String(educationLevel) : undefined,
      hasBPLCard: Boolean(hasBPLCard)
    };

    const allSchemes = db.getSchemes().filter(s => s.isPublished && !s.isArchived);
    const evaluatedResults = allSchemes.map(scheme => evaluateEligibility(scheme, input));

    // Sort: Eligible first with highest score, then partially eligible
    evaluatedResults.sort((a, b) => b.matchScore - a.matchScore);

    const eligibleSchemes = evaluatedResults.filter(r => r.isEligible);
    const partiallyEligible = evaluatedResults.filter(r => !r.isEligible && r.matchScore >= 40);

    // Save assessment record
    const assessment: EligibilityAssessment = {
      id: `assess-${Date.now()}`,
      userId: req.user?.id,
      timestamp: new Date().toISOString(),
      inputCriteria: {
        age: input.age,
        state: input.state,
        occupation: input.occupation,
        beneficiaryCategory: input.beneficiaryCategory,
        annualIncome: input.annualIncome,
        educationLevel: input.educationLevel
      },
      eligibleSchemesCount: eligibleSchemes.length
    };
    db.saveAssessment(assessment);

    return res.json({
      success: true,
      disclaimer: "Official Disclaimer: Eligibility assessment generated by JANASEVA is based on verified public scheme guidelines and is intended for preliminary advisory purposes. Final benefit sanction is subject to document scrutiny and approval by the designated government department or authority.",
      totalEvaluated: allSchemes.length,
      eligibleCount: eligibleSchemes.length,
      eligibleSchemes,
      partiallyEligible
    });
  } catch (err) {
    console.error('Eligibility check error:', err);
    return res.status(500).json({ success: false, message: 'Server error processing eligibility check.' });
  }
});

// GET /api/eligibility/history
router.get('/history', optionalAuthenticate, (req: AuthenticatedRequest, res: Response) => {
  if (!req.user) {
    return res.json({ success: true, history: [] });
  }
  const history = db.getUserAssessments(req.user.id);
  return res.json({ success: true, history });
});

export default router;
