import React, { useState, useEffect, useMemo } from 'react';
import { Link, useNavigate } from 'react-router-dom';
import {
  History, CheckCircle2, AlertCircle, Trash2, ArrowRight,
  FileCheck, ShieldCheck, Sparkles, RefreshCw, Calendar,
  Search, Filter, Info, ArrowUpRight
} from 'lucide-react';
import { api } from '../../services/api';
import { SavedEligibilityRecord } from '../../types';

export const EligibilityHistoryPage: React.FC = () => {
  const [history, setHistory] = useState<SavedEligibilityRecord[]>([]);
  const [loading, setLoading] = useState(true);
  const [searchQuery, setSearchQuery] = useState('');
  const [selectedCategory, setSelectedCategory] = useState<string>('All');
  const [toastMessage, setToastMessage] = useState<string | null>(null);
  const navigate = useNavigate();

  const loadHistory = async () => {
    setLoading(true);
    try {
      const res = await api.getEligibilityHistory();
      if (res.success && res.history) {
        setHistory(res.history);
      }
    } catch (e) {
      console.warn('Failed loading eligibility history:', e);
    } finally {
      setLoading(false);
    }
  };

  useEffect(() => {
    loadHistory();
  }, []);

  const handleDelete = async (id: string, schemeName: string) => {
    const ok = window.confirm(`Remove eligibility evaluation for "${schemeName}" from your history?`);
    if (ok) {
      await api.deleteEligibilityHistory(id);
      setHistory(prev => prev.filter(h => h.id !== id));
      setToastMessage(`Evaluation for "${schemeName}" removed from history.`);
      setTimeout(() => setToastMessage(null), 3000);
    }
  };

  // Summary statistics
  const totalEvaluations = history.length;
  const eligibleCount = history.filter(h => h.isEligible || h.matchScore >= 80).length;
  const partialCount = history.filter(h => !h.isEligible && h.matchScore < 80).length;
  const avgMatch = totalEvaluations > 0
    ? Math.round(history.reduce((acc, h) => acc + (h.matchScore || 0), 0) / totalEvaluations)
    : 0;

  const categories = useMemo(() => {
    const set = new Set<string>();
    history.forEach(h => {
      if (h.category) set.add(h.category);
    });
    return ['All', ...Array.from(set)];
  }, [history]);

  const filteredHistory = useMemo(() => {
    return history.filter(h => {
      const matchesSearch =
        h.schemeName.toLowerCase().includes(searchQuery.toLowerCase()) ||
        (h.category && h.category.toLowerCase().includes(searchQuery.toLowerCase()));

      const matchesCat = selectedCategory === 'All' || h.category === selectedCategory;
      return matchesSearch && matchesCat;
    });
  }, [history, searchQuery, selectedCategory]);

  return (
    <div className="p-4 sm:p-6 lg:p-8 space-y-6 max-w-7xl mx-auto">
      {/* Toast Alert */}
      {toastMessage && (
        <div className="fixed bottom-6 right-6 z-50 p-4 rounded-2xl bg-[#101016] border border-[#1ed760]/30 text-[#1ed760] text-xs shadow-2xl flex items-center space-x-2 animate-in slide-in-from-bottom duration-200">
          <CheckCircle2 className="w-4 h-4" />
          <span>{toastMessage}</span>
        </div>
      )}

      {/* Advisory Banner */}
      <div className="p-4 rounded-2xl bg-[#f3c64f]/10 border border-[#f3c64f]/25 text-white text-xs flex items-start space-x-3">
        <Info className="w-5 h-5 text-[#f3c64f] shrink-0 mt-0.5" />
        <div className="space-y-0.5">
          <p className="font-semibold text-[#f3c64f]">Preliminary Advisory Notice</p>
          <p className="text-[#b6b6c2] leading-relaxed">
            Preliminary eligibility calculations generated by JANASEVA&apos;s deterministic engine are for citizen advisory guidance based on self-reported demographics. Final sanction and DBT disbursement depend strictly on official document verification by the relevant administrative department.
          </p>
        </div>
      </div>

      {/* Header */}
      <div className="flex flex-col sm:flex-row sm:items-center justify-between gap-4">
        <div>
          <div className="flex items-center space-x-2">
            <h1 className="text-xl sm:text-2xl font-bold text-white tracking-tight">Saved Eligibility Evaluations</h1>
            <span className="text-xs font-semibold px-2.5 py-0.5 rounded-full bg-[#1ed760]/15 text-[#1ed760] border border-[#1ed760]/30">
              {totalEvaluations} Assessments
            </span>
          </div>
          <p className="text-xs text-[#8a8a97] mt-1">
            Historical evaluations stored with your consent. Review condition matches, required certificates, or re-run checks.
          </p>
        </div>

        <Link
          to="/eligibility"
          className="inline-flex items-center space-x-2 px-4 py-2.5 rounded-xl bg-gradient-to-r from-[#8f8bff] to-[#6fd8ff] text-[#050507] text-xs font-semibold transition-all cursor-pointer hover:opacity-90 shadow-md self-start sm:self-auto"
        >
          <Sparkles className="w-4 h-4" />
          <span>Run New Eligibility Check</span>
        </Link>
      </div>

      {/* Summary Statistics Cards */}
      <div className="grid grid-cols-2 lg:grid-cols-4 gap-4">
        <div className="p-4 rounded-2xl bg-white/[0.03] border border-white/[0.08]">
          <p className="text-xs text-[#8a8a97]">Total Evaluated</p>
          <p className="text-2xl font-bold text-white mt-1">{totalEvaluations}</p>
          <p className="text-[11px] text-[#8a8a97] mt-0.5">Schemes checked</p>
        </div>

        <div className="p-4 rounded-2xl bg-white/[0.03] border border-white/[0.08]">
          <p className="text-xs text-[#8a8a97]">Likely Eligible</p>
          <p className="text-2xl font-bold text-[#1ed760] mt-1">{eligibleCount}</p>
          <p className="text-[11px] text-[#8a8a97] mt-0.5">Met all key rules</p>
        </div>

        <div className="p-4 rounded-2xl bg-white/[0.03] border border-white/[0.08]">
          <p className="text-xs text-[#8a8a97]">Partially Eligible</p>
          <p className="text-2xl font-bold text-[#f3c64f] mt-1">{partialCount}</p>
          <p className="text-[11px] text-[#8a8a97] mt-0.5">Conditionally matched</p>
        </div>

        <div className="p-4 rounded-2xl bg-white/[0.03] border border-white/[0.08]">
          <p className="text-xs text-[#8a8a97]">Average Compatibility</p>
          <p className="text-2xl font-bold text-[#8f8bff] mt-1">{avgMatch}%</p>
          <p className="text-[11px] text-[#8a8a97] mt-0.5">Across all assessments</p>
        </div>
      </div>

      {/* Search & Category Filter Bar */}
      {history.length > 0 && (
        <div className="p-4 rounded-2xl bg-[#0c0c12] border border-white/10 space-y-3">
          <div className="relative">
            <input
              type="text"
              value={searchQuery}
              onChange={(e) => setSearchQuery(e.target.value)}
              placeholder="Search evaluations by scheme title or category..."
              className="w-full h-10 pl-10 pr-4 rounded-xl bg-white/[0.04] border border-white/10 text-white placeholder:text-[#8a8a97] text-xs focus:outline-none focus:border-[#8f8bff]"
            />
            <Search className="w-4 h-4 text-[#8a8a97] absolute left-3.5 top-3" />
          </div>

          {categories.length > 2 && (
            <div className="flex items-center space-x-2 overflow-x-auto pb-1">
              {categories.map((cat) => (
                <button
                  key={cat}
                  onClick={() => setSelectedCategory(cat)}
                  className={`px-3 py-1.5 rounded-full text-[11px] font-medium transition-all cursor-pointer whitespace-nowrap ${
                    selectedCategory === cat
                      ? 'bg-[#8f8bff] text-[#050507] font-semibold'
                      : 'bg-white/[0.04] text-[#b6b6c2] hover:text-white border border-white/5'
                  }`}
                >
                  {cat}
                </button>
              ))}
            </div>
          )}
        </div>
      )}

      {loading ? (
        <div className="space-y-4">
          {[1, 2].map(i => (
            <div key={i} className="h-44 rounded-3xl bg-white/[0.02] border border-white/5 animate-pulse" />
          ))}
        </div>
      ) : filteredHistory.length === 0 ? (
        <div className="p-12 rounded-3xl bg-[#0c0c12] border border-white/10 text-center space-y-4">
          <div className="w-16 h-16 rounded-2xl bg-[#1ed760]/10 text-[#1ed760] flex items-center justify-center mx-auto border border-[#1ed760]/20">
            <History className="w-8 h-8 opacity-60" />
          </div>
          <div className="space-y-1">
            <h3 className="text-base font-bold text-white">
              {searchQuery ? 'No Matching Evaluation Records' : 'No Saved Eligibility Assessments'}
            </h3>
            <p className="text-xs text-[#8a8a97] max-w-md mx-auto">
              {searchQuery
                ? 'Try adjusting your search keyword or clearing the active category filter.'
                : 'Run an eligibility check to evaluate age, income, and state criteria, then save your results for future reference.'}
            </p>
          </div>
          <Link
            to="/eligibility"
            className="inline-flex items-center space-x-2 px-4 py-2 rounded-xl bg-gradient-to-r from-[#8f8bff] to-[#6fd8ff] text-[#050507] text-xs font-semibold cursor-pointer"
          >
            <span>Check My Scheme Eligibility</span>
            <ArrowRight className="w-3.5 h-3.5" />
          </Link>
        </div>
      ) : (
        <div className="space-y-4">
          {filteredHistory.map((record) => (
            <div
              key={record.id}
              className="p-6 rounded-3xl bg-[#0c0c12] border border-white/10 hover:border-white/20 transition-all space-y-4"
            >
              {/* Header row: Scheme name + match score */}
              <div className="flex flex-col sm:flex-row sm:items-center justify-between gap-3">
                <div className="space-y-1">
                  <div className="flex items-center space-x-2">
                    <span className="text-[10px] uppercase font-bold tracking-wider px-2 py-0.5 rounded-full bg-white/[0.06] text-[#6fd8ff]">
                      {record.category}
                    </span>
                    <span className="text-xs text-[#8a8a97] flex items-center space-x-1">
                      <Calendar className="w-3 h-3" />
                      <span>{new Date(record.evaluatedAt).toLocaleDateString()}</span>
                    </span>
                  </div>
                  <h3 className="text-base font-bold text-white">{record.schemeName}</h3>
                </div>

                <div className="flex items-center space-x-3 self-start sm:self-auto">
                  <div className={`px-3 py-1.5 rounded-2xl border text-center ${
                    record.isEligible || record.matchScore >= 80
                      ? 'bg-[#1ed760]/15 border-[#1ed760]/30 text-[#1ed760]'
                      : 'bg-[#f3c64f]/15 border-[#f3c64f]/30 text-[#f3c64f]'
                  }`}>
                    <span className="text-xs font-bold block">{record.matchScore}% Match</span>
                    <span className="text-[10px]">
                      {record.isEligible || record.matchScore >= 80 ? 'Likely Eligible' : 'Partially Eligible'}
                    </span>
                  </div>

                  <button
                    onClick={() => handleDelete(record.id, record.schemeName)}
                    className="p-2 rounded-xl bg-white/5 hover:bg-rose-500/10 text-[#8a8a97] hover:text-rose-400 transition-colors cursor-pointer"
                    title="Remove from history"
                  >
                    <Trash2 className="w-4 h-4" />
                  </button>
                </div>
              </div>

              {/* Evaluated Demographic Criteria Chips */}
              {record.inputCriteria && (
                <div className="p-3 rounded-2xl bg-white/[0.02] border border-white/5 flex flex-wrap gap-x-4 gap-y-1 text-xs text-[#8a8a97]">
                  <span>Age: <strong className="text-white">{record.inputCriteria.age}</strong></span>
                  <span>State: <strong className="text-white">{record.inputCriteria.state}</strong></span>
                  <span>Occupation: <strong className="text-white">{record.inputCriteria.occupation}</strong></span>
                  <span>Category: <strong className="text-white">{record.inputCriteria.beneficiaryCategory}</strong></span>
                  <span>Annual Income: <strong className="text-white">₹{record.inputCriteria.annualIncome?.toLocaleString('en-IN') || '0'}</strong></span>
                </div>
              )}

              {/* Matching & Unmet Conditions */}
              <div className="grid grid-cols-1 md:grid-cols-2 gap-4 text-xs">
                {record.matchingReasons && record.matchingReasons.length > 0 && (
                  <div className="space-y-1.5">
                    <p className="font-semibold text-[#1ed760] flex items-center space-x-1">
                      <CheckCircle2 className="w-3.5 h-3.5" />
                      <span>Satisfied Criteria ({record.matchingReasons.length})</span>
                    </p>
                    <ul className="space-y-1 text-[#b6b6c2]">
                      {record.matchingReasons.map((r, idx) => (
                        <li key={idx} className="flex items-start space-x-1.5">
                          <span className="text-[#1ed760] mt-0.5">•</span>
                          <span>{r}</span>
                        </li>
                      ))}
                    </ul>
                  </div>
                )}

                {record.unmetConditions && record.unmetConditions.length > 0 && (
                  <div className="space-y-1.5">
                    <p className="font-semibold text-[#f3c64f] flex items-center space-x-1">
                      <AlertCircle className="w-3.5 h-3.5" />
                      <span>Unmet Criteria / Discrepancies ({record.unmetConditions.length})</span>
                    </p>
                    <ul className="space-y-1 text-[#b6b6c2]">
                      {record.unmetConditions.map((u, idx) => (
                        <li key={idx} className="flex items-start space-x-1.5">
                          <span className="text-[#f3c64f] mt-0.5">•</span>
                          <span>{u}</span>
                        </li>
                      ))}
                    </ul>
                  </div>
                )}
              </div>

              {/* Required Documents */}
              {record.requiredDocuments && record.requiredDocuments.length > 0 && (
                <div className="pt-2 border-t border-white/5 space-y-1">
                  <p className="text-[11px] font-semibold text-[#8a8a97]">Mandatory Documentation Required:</p>
                  <div className="flex flex-wrap gap-1.5">
                    {record.requiredDocuments.map((doc, idx) => (
                      <span key={idx} className="text-[11px] px-2.5 py-0.5 rounded-lg bg-white/[0.04] text-[#b6b6c2] border border-white/5">
                        {doc}
                      </span>
                    ))}
                  </div>
                </div>
              )}

              {/* Recheck Action */}
              <div className="pt-2 flex justify-end">
                <Link
                  to="/eligibility"
                  className="inline-flex items-center space-x-1.5 text-xs text-[#8f8bff] font-semibold hover:underline"
                >
                  <RefreshCw className="w-3 h-3" />
                  <span>Re-evaluate With Updated Criteria</span>
                </Link>
              </div>
            </div>
          ))}
        </div>
      )}
    </div>
  );
};
